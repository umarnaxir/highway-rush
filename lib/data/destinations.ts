export const DESTINATIONS_BY_ID: Record<string, DestinationDefinition> = Object.fromEntries(
  DESTINATIONS.map((destination) => [destination.id, destination]),
);

export function meetsDestinationRequirement(
  destination: DestinationDefinition,
  stats: { racesCompleted: number },
  trophies: number,
): { met: boolean; missing: string[] } {
  const missing: string[] = [];
  if (destination.requirement?.races && stats.racesCompleted < destination.requirement.races) {
    missing.push(`${destination.requirement.races} races completed`);
  }
  if (destination.requirement?.trophies && trophies < destination.requirement.trophies) {
    missing.push(`${destination.requirement.trophies} trophies`);
  }
  return { met: missing.length === 0, missing };
}
